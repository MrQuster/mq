impl Language {
    pub const ALL: [Self; 11] = [
        Self::Ukrainian,
        Self::Russian,
        Self::English,
        Self::Polish,
        Self::German,
        Self::Spanish,
        Self::French,
        Self::Belarusian,
        Self::Kazakh,
        Self::ChineseSimplified,
        Self::Japanese,
    ];

    pub const fn code(&self) -> &'static str {
        match self {
            Self::Ukrainian => "uk_UA",
            Self::Russian => "ru_RU",
            Self::English => "en_US",
            Self::Polish => "pl_PL",
            Self::German => "de_DE",
            Self::Spanish => "es_ES",
            Self::French => "fr_FR",
            Self::Belarusian => "be_BY",
            Self::Kazakh => "kk_KZ",
            Self::ChineseSimplified => "zh_CN",
            Self::Japanese => "ja_JP",
        }
    }

    pub const fn native_name(&self) -> &'static str {
        match self {
            Self::Ukrainian => "Українська",
            Self::Russian => "Русский",
            Self::English => "English",
            Self::Polish => "Polski",
            Self::German => "Deutsch",
            Self::Spanish => "Español",
            Self::French => "Français",
            Self::Belarusian => "Беларуская",
            Self::Kazakh => "Қазақша",
            Self::ChineseSimplified => "简体中文",
            Self::Japanese => "日本語",
        }
    }

    pub fn from_code(code: &str) -> Self {
        match code.trim() {
            "uk_UA" | "uk_ua" | "uk" => Self::Ukrainian,
            "ru_RU" | "ru_ru" | "ru" => Self::Russian,
            "pl_PL" | "pl_pl" | "pl" => Self::Polish,
            "de_DE" | "de_de" | "de" => Self::German,
            "es_ES" | "es_es" | "es" => Self::Spanish,
            "fr_FR" | "fr_fr" | "fr" => Self::French,
            "be_BY" | "be_by" | "be" => Self::Belarusian,
            "kk_KZ" | "kk_kz" | "kk" => Self::Kazakh,
            "zh_CN" | "zh_cn" | "zh" => Self::ChineseSimplified,
            "ja_JP" | "ja_jp" | "ja" => Self::Japanese,
            _ => Self::English,
        }
    }
}

